#!/usr/bin/env python3
"""Turns display.json and the art/<name>/NN.pbm frames into C for the
firmware. The build runs this, so only the frames and settings live in git.

    python3 build_art.py <shield dir> <output dir>

Frames are drawn upright (68x68, as the screen is read), and stored rotated
the way the nice!view is mounted: its 160x68 panel stands on end, so the
panel's right edge is the top of the picture (or its left edge, flipped).
"""

import json
import os
import re
import sys

SIZE = 68
MODES = {"off": 0, "layer-change": 1, "active": 2}


def read_pbm(path):
    data = open(path, "rb").read()
    tokens = []
    pos = 0
    # Header: magic, width, height, with # comments allowed between them.
    while len(tokens) < 3:
        while data[pos : pos + 1].isspace():
            pos += 1
        if data[pos : pos + 1] == b"#":
            pos = data.index(b"\n", pos) + 1
            continue
        start = pos
        while not data[pos : pos + 1].isspace():
            pos += 1
        tokens.append(data[start:pos].decode())
    magic, w, h = tokens[0], int(tokens[1]), int(tokens[2])
    if (w, h) != (SIZE, SIZE):
        raise SystemExit("%s is %dx%d; frames must be %dx%d" % (path, w, h, SIZE, SIZE))
    pixels = [[0] * w for _ in range(h)]
    if magic == "P4":
        pos += 1
        stride = (w + 7) // 8
        for y in range(h):
            for x in range(w):
                pixels[y][x] = (data[pos + y * stride + x // 8] >> (7 - x % 8)) & 1
    elif magic == "P1":
        bits = re.findall(rb"[01]", re.sub(rb"#[^\n]*", b"", data[pos:]))
        for i in range(w * h):
            pixels[i // w][i % w] = int(bits[i])
    else:
        raise SystemExit("%s isn't a PBM image" % path)
    return pixels


def rotate(pixels, flip):
    """Upright picture to panel layout: a quarter turn clockwise, or counter-clockwise when flipped."""
    n = len(pixels)
    out = [[0] * n for _ in range(n)]
    for y in range(n):
        for x in range(n):
            if flip:
                out[n - 1 - x][y] = pixels[y][x]
            else:
                out[x][n - 1 - y] = pixels[y][x]
    return out


def pack(pixels):
    """LVGL I1: a two-color palette, then rows of bits. Ink (1 in a PBM)
    becomes palette index 0, matching ZMK's own nice!view art."""
    out = []
    for row in pixels:
        byte, bits = 0, 0
        for v in row:
            byte = (byte << 1) | (0 if v else 1)
            bits += 1
            if bits == 8:
                out.append(byte)
                byte, bits = 0, 0
        if bits:
            out.append((byte << (8 - bits)) | ((1 << (8 - bits)) - 1))
    return out


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ident(name):
    return re.sub(r"[^a-zA-Z0-9_]", "_", name)


def main():
    shield, out_dir = sys.argv[1], sys.argv[2]
    settings = json.load(open(os.path.join(shield, "display.json")))
    flip = bool(settings.get("flip", False))
    invert = bool(settings.get("invert", False))
    mode = MODES.get(settings.get("animate", "active"), 2)
    fps = max(1, min(20, int(settings.get("fps", 8))))
    layers = settings.get("layers", [])

    art_dir = os.path.join(shield, "art")
    names = sorted(d for d in os.listdir(art_dir) if os.path.isdir(os.path.join(art_dir, d)))
    anims = []
    for name in names:
        frames = sorted(f for f in os.listdir(os.path.join(art_dir, name)) if f.endswith(".pbm"))
        if frames:
            anims.append((name, [os.path.join(art_dir, name, f) for f in frames]))
    if not anims:
        raise SystemExit("No art found in %s" % art_dir)
    index = {name: i for i, (name, _) in enumerate(anims)}

    stride = (SIZE + 7) // 8
    palette = ["0xff, 0xff, 0xff, 0xff", "0x00, 0x00, 0x00, 0xff"] if invert else [
        "0x00, 0x00, 0x00, 0xff", "0xff, 0xff, 0xff, 0xff"]

    c = ["/* Generated by build_art.py from display.json and art/. Don't edit. */", "",
         "#include <lvgl.h>", '#include "art.h"', ""]
    for name, frames in anims:
        refs = []
        for i, path in enumerate(frames):
            sym = "%s_%02d" % (ident(name), i)
            data = pack(rotate(read_pbm(path), flip))
            c.append("static const uint8_t %s_map[] = {" % sym)
            c.append("    %s, %s," % tuple(palette))
            for k in range(0, len(data), 16):
                c.append("    " + ", ".join("0x%02x" % b for b in data[k : k + 16]) + ",")
            c.append("};")
            c.append("static const lv_image_dsc_t %s = {" % sym)
            c.append("    .header.magic = LV_IMAGE_HEADER_MAGIC,")
            c.append("    .header.cf = LV_COLOR_FORMAT_I1,")
            c.append("    .header.w = %d," % SIZE)
            c.append("    .header.h = %d," % SIZE)
            c.append("    .header.stride = %d," % stride)
            c.append("    .data_size = %d," % (8 + len(data)))
            c.append("    .data = %s_map," % sym)
            c.append("};")
            refs.append("&" + sym)
        c.append("static const lv_image_dsc_t *const %s_frames[] = {%s};" % (ident(name), ", ".join(refs)))
        c.append("")
    c.append("const struct sweep_view_anim sweep_view_anims[] = {")
    for name, frames in anims:
        c.append("    {%s, %s_frames, %d}," % (c_string(name), ident(name), len(frames)))
    c.append("};")
    c.append("const uint8_t sweep_view_anim_count = %d;" % len(anims))
    c.append("")
    layer_anims = [str(index.get(l.get("art", ""), 0)) for l in layers] or ["0"]
    layer_names = [c_string(l.get("name", "")) for l in layers] or ['""']
    c.append("const uint8_t sweep_view_layer_anim[] = {%s};" % ", ".join(layer_anims))
    c.append("const char *const sweep_view_layer_names[] = {%s};" % ", ".join(layer_names))
    c.append("const uint8_t sweep_view_layer_count = %d;" % len(layers))
    c.append("")

    h = ["/* Generated by build_art.py from display.json. Don't edit. */", "#pragma once", "",
         "#include <lvgl.h>", "",
         "#define SWEEP_VIEW_MODE_OFF 0",
         "#define SWEEP_VIEW_MODE_LAYER_CHANGE 1",
         "#define SWEEP_VIEW_MODE_ACTIVE 2",
         "#define SWEEP_VIEW_MODE %d" % mode,
         "#define SWEEP_VIEW_FPS %d" % fps,
         "#define SWEEP_VIEW_FLIP %d" % int(flip),
         "#define SWEEP_VIEW_INVERT %d" % int(invert),
         "#define SWEEP_VIEW_ART_SIZE %d" % SIZE, "",
         "struct sweep_view_anim {",
         "    const char *name;",
         "    const lv_image_dsc_t *const *frames;",
         "    uint8_t count;",
         "};", "",
         "extern const struct sweep_view_anim sweep_view_anims[];",
         "extern const uint8_t sweep_view_anim_count;",
         "extern const uint8_t sweep_view_layer_anim[];",
         "extern const char *const sweep_view_layer_names[];",
         "extern const uint8_t sweep_view_layer_count;", ""]

    os.makedirs(out_dir, exist_ok=True)
    for filename, lines in (("art.c", c), ("art.h", h)):
        path = os.path.join(out_dir, filename)
        text = "\n".join(lines) + "\n"
        if not os.path.exists(path) or open(path).read() != text:
            with open(path, "w") as out:
                out.write(text)


if __name__ == "__main__":
    main()
